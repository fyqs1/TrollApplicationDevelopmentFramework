USAGE_INFO_KEYS = {
    "location": "NSLocationWhenInUseUsageDescription",
    "local_network": "NSLocalNetworkUsageDescription",
    "camera": "NSCameraUsageDescription",
    "microphone": "NSMicrophoneUsageDescription",
    "photos": "NSPhotoLibraryUsageDescription",
    "tracking": "NSUserTrackingUsageDescription",
}


def app_entitlements(cfg: TrollAppConfig) -> dict[str, Any]:
    catalog = capmod.load_catalog()
    blobs = [catalog[cap_id].entitlements for cap_id in cfg.capabilities]
    blobs.append(
        {
            "application-identifier": cfg.bundle_id,
            "com.apple.developer.team-identifier": cfg.team_id,
        }
    )
    blobs.append(cfg.extra_entitlements)
    return capmod.merge_entitlements(blobs)


def tunnel_entitlements(cfg: TrollAppConfig) -> dict[str, Any]:
    catalog = capmod.load_catalog()
    blobs = [catalog[cap_id].tunnel_entitlements for cap_id in cfg.capabilities]
    blobs.append(
        {
            "application-identifier": cfg.packet_tunnel.bundle_id(cfg.bundle_id),
            "com.apple.developer.team-identifier": cfg.team_id,
            "get-task-allow": True,
            "platform-application": True,
            "com.apple.private.security.no-sandbox": True,
            "com.apple.private.security.container-required": False,
            "com.apple.developer.networking.networkextension": ["packet-tunnel-provider"],
        }
    )
    blobs.append(cfg.extra_tunnel_entitlements)
    return capmod.merge_entitlements([blob for blob in blobs if blob])


def info_plist(cfg: TrollAppConfig) -> dict[str, Any]:
    plist: dict[str, Any] = {
        "CFBundleDevelopmentRegion": "$(DEVELOPMENT_LANGUAGE)",
        "CFBundleDisplayName": cfg.display_name,
        "CFBundleExecutable": "$(EXECUTABLE_NAME)",
        "CFBundleIdentifier": "$(PRODUCT_BUNDLE_IDENTIFIER)",
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": "$(PRODUCT_NAME)",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": cfg.version,
        "CFBundleVersion": cfg.build,
        "UILaunchScreen": {},
        "UISupportedInterfaceOrientations": [
            "UIInterfaceOrientationPortrait",
            "UIInterfaceOrientationPortraitUpsideDown",
            "UIInterfaceOrientationLandscapeLeft",
            "UIInterfaceOrientationLandscapeRight",
        ],
        "UISupportedInterfaceOrientations~ipad": [
            "UIInterfaceOrientationPortrait",
            "UIInterfaceOrientationPortraitUpsideDown",
            "UIInterfaceOrientationLandscapeLeft",
            "UIInterfaceOrientationLandscapeRight",
        ],
    }
    if cfg.query_schemes:
        plist["LSApplicationQueriesSchemes"] = list(cfg.query_schemes)
    for usage_key, text in cfg.usage.items():
        plist[USAGE_INFO_KEYS.get(usage_key, usage_key)] = text
    plist.update(cfg.extra_info)
    return plist


