def capabilities_swift(cfg: TrollAppConfig) -> str:
    catalog = capmod.load_catalog()
    resolved = set(cfg.capabilities)
    flags = [
        f"    static let {capmod.swift_flag_name(cap_id)} = {_swift_bool(cap_id in resolved)}"
        for cap_id in sorted(catalog)
    ]
    cap_list = ", ".join(f'"{item}"' for item in cfg.capabilities)
    return (
        f"// GENERATED by {FRAMEWORK_SHORT} {__version__}. Do not edit.\n"
        "// Source of truth: trollapp.yml\n\n"
        "enum TADF {\n"
        f'    static let framework = "{FRAMEWORK_SHORT}"\n'
        f'    static let appName = "{_swift_str(cfg.name)}"\n'
        f'    static let displayName = "{_swift_str(cfg.display_name)}"\n'
        f'    static let bundleID = "{_swift_str(cfg.bundle_id)}"\n'
        f'    static let version = "{_swift_str(cfg.version)}"\n'
        f'    static let build = "{_swift_str(cfg.build)}"\n'
        f'    static let channel = "{_swift_str(cfg.channel)}"\n'
        f'    static let minIOS = "{_swift_str(cfg.min_ios)}"\n'
        f"    static let capabilityList: [String] = [{cap_list}]\n"
        + "\n".join(flags)
        + "\n}\n"
    )


def project_yml(cfg: TrollAppConfig) -> str:
    lines = [
        f"# GENERATED by {FRAMEWORK_SHORT} from trollapp.yml. Do not edit.",
        f"name: {cfg.name}",
        "options:",
        f"  bundleIdPrefix: {_bundle_prefix(cfg.bundle_id)}",
        "  deploymentTarget:",
        f'    iOS: "{cfg.min_ios}"',
        "  createIntermediateGroups: true",
        "  developmentLanguage: en",
        "settings:",
        "  base:",
        f"    PRODUCT_BUNDLE_IDENTIFIER: {cfg.bundle_id}",
        f"    PRODUCT_NAME: {cfg.name}",
        f'    MARKETING_VERSION: "{cfg.version}"',
        f'    CURRENT_PROJECT_VERSION: "{cfg.build}"',
        '    TARGETED_DEVICE_FAMILY: "1,2"',
        f'    SWIFT_VERSION: "{cfg.swift_version}"',
        f'    IPHONEOS_DEPLOYMENT_TARGET: "{cfg.min_ios}"',
        "    CODE_SIGN_STYLE: Manual",
        '    CODE_SIGNING_ALLOWED: "NO"',
        '    CODE_SIGNING_REQUIRED: "NO"',
        '    CODE_SIGN_IDENTITY: ""',
        '    DEVELOPMENT_TEAM: ""',
        '    ONLY_ACTIVE_ARCH: "NO"',
        '    SUPPORTS_MACCATALYST: "NO"',
    ]
    if cfg.packages:
        lines.append("packages:")
        lines.extend(_packages_block(cfg))
    lines.append("targets:")
    if cfg.packet_tunnel.enabled:
        lines.extend(_packet_tunnel_target(cfg))
    lines.extend(_app_target(cfg))
    return "\n".join(lines) + "\n"


def _packages_block(cfg: TrollAppConfig) -> list[str]:
    lines: list[str] = []
    for pkg in cfg.packages:
        lines.append(f"  {pkg.name}:")
        if pkg.path:
            lines.append(f"    path: {pkg.path}")
            continue
        lines.append(f"    url: {pkg.url}")
        if pkg.revision:
            lines.append(f"    revision: {pkg.revision}")
        elif pkg.branch:
            lines.append(f"    branch: {pkg.branch}")
        elif pkg.exact:
            lines.append(f'    exactVersion: "{pkg.exact}"')
        else:
            version = pkg.from_version or "1.0.0"
            lines.append(f'    from: "{version}"')
    return lines


